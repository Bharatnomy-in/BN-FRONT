"""Generated documents: the state README, ATTRIBUTION.md and CHANGELOG entries."""
from __future__ import annotations

import re
import subprocess
from datetime import date
from pathlib import Path

import pandas as pd

from .config import ROOT, Config, State
from .readme import WAREHOUSE_WEB, _cell, parse_readme

# Where the public downloads raw files from (GitHub "raw" URLs on the main branch).
FRONT_REPO_RAW = "https://raw.githubusercontent.com/sarveshkant2003-afk/bharatnomy-front/main"
BOUNDARY_README = "_sources/datameet-maps/README.md"


def _period_end(period: str) -> str:
    return period.split("-to-")[-1]


def state_readme(state: State, state_name: str, cfg: Config, datasets: list[dict], warehouse: Path,
                 sha: str, lens_names: dict[str, str], profile_cols: pd.DataFrame, boundary_notes: list[str]) -> str:
    entries = [d for d in datasets if d["state"] == state.slug]
    titles = {d["dataset"]: parse_readme(warehouse / d["warehouse_parts"][-1] / "README.md", d["warehouse_parts"][-1], sha).title.replace(", India,", ",")
              for d in entries}
    # Projections (e.g. built-up 2030) are not "data as of"; cap at the warehouse commit's year
    # (from git, so the output stays the same for the same commit).
    commit_year = int(subprocess.run(["git", "show", "-s", "--format=%cs", sha], cwd=warehouse,
                                     capture_output=True, text=True, check=True).stdout[:4])
    ends = [_period_end(d["dataset"].split("_")[2]) for d in entries]
    as_of = max((e for e in ends if int(e[:4]) <= commit_year), default="")
    base = f"states/{state.slug}"
    lines = [
        f"# {state_name}: district data",
        "",
        f"District-level tables for {state_name}, organised by Bharatnomy's lenses. Generated by `build.py`; do not edit.",
        "",
        f"- **Datasets:** {len(entries)}",
        f"- **Data as of:** {as_of} (latest observed period across datasets, projections excluded; each table has its own period)",
        f"- **Warehouse commit:** [`{sha[:12]}`]({WAREHOUSE_WEB}/tree/{sha})",
        "",
        "## Files for maps",
        "",
        f"- [`district-profile.csv`](district-profile.csv) / [`.json`](district-profile.json): one row per district "
        f"({len(profile_cols)} indicators, each with a `_year` column saying which year was used). Empty = no value, never zero.",
        "- [`districts.geojson`](districts.geojson): district boundaries (Census 2011, DataMeet), joined on `lgd_district_code`.",
    ]
    lines += [f"  - {note}" for note in boundary_notes]
    lines += ["", "### Profile indicators", "", "| Column | Indicator | Unit | From |", "|---|---|---|---|"]
    for ind in profile_cols.to_dict("records"):
        lines.append(f"| `{ind['indicator_id']}` | {_cell(ind['label'])} | {ind['unit']} | `{ind['dataset']}` → `{ind['column']}` |")
    lines.append("")
    for lens_id, folder in cfg.lens_folders.items():
        in_lens = [d for d in entries if d["lens"] == lens_id]
        lines += [f"## {lens_names.get(lens_id, lens_id)} (`{folder}/`)", ""]
        if not in_lens:
            lines += ["No district-level data for this lens yet.", ""]
            continue
        lines += ["| Dataset | What it holds | Period | Rows |", "|---|---|---|---|"]
        for d in in_lens:
            period = d["dataset"].split("_")[2].replace("-to-", " to ")
            lines.append(f"| [`{d['dataset']}`]({folder}/{d['dataset']}/) | {_cell(titles[d['dataset']])} | {period} | {d['rows']:,} |")
        lines.append("")
    example = entries[0] if entries else None
    lines += [
        "## How to use",
        "",
        "- Join tables to each other and to the map on **`lgd_district_code`** (text), not on district names.",
        "- Every dataset folder has a CSV, a JSON (array of row objects; codes are strings, numbers are numbers, missing = `null`) and a README with sources and column meanings.",
        "- Raw-file URLs (for code or direct download):",
        "",
        "```",
        f"{FRONT_REPO_RAW}/{base}/district-profile.csv",
        f"{FRONT_REPO_RAW}/{base}/districts.geojson",
    ]
    if example:
        lines.append(f"{FRONT_REPO_RAW}/{example['path']}/{example['dataset']}.csv")
    lines += ["```", ""]
    return "\n".join(lines)


def attribution(datasets: list[dict], warehouse: Path, sha: str) -> str:
    """Every original source (Data line + Link line of each warehouse README), with the datasets using it."""
    sources: dict[tuple[str, str], set[str]] = {}
    readmes = {p: warehouse / p / "README.md" for d in datasets for p in d["warehouse_parts"]}
    readmes["districts.geojson"] = warehouse / BOUNDARY_README
    used_by = {p: d["dataset"] for d in datasets for p in d["warehouse_parts"]}
    for part, path in sorted(readmes.items()):
        source = parse_readme(path, part, sha).sections.get("Source", "")
        data = re.search(r"^- \*\*Data:\*\* (.+)$", source, re.M)
        link = re.search(r"^- \*\*Link:\*\* (.+)$", source, re.M)
        licence = re.search(r"^- \*\*Licen[cs]e:\*\* (.+)$", source, re.M)
        key = (data.group(1).strip() if data else part, link.group(1).strip() if link else "")
        label = used_by.get(part, part)
        sources.setdefault(key, set()).add(label)
        if licence:
            sources.setdefault(key, set()).add(f"licence: {licence.group(1).strip()}")
    lines = [
        "# Attribution",
        "",
        "Generated by `build.py` from the warehouse READMEs. Do not edit.",
        "",
        "Government and third-party source data keep their original terms of use. "
        "Tables marked `BNY` in their name are Bharatnomy's own calculations from these sources (see [LICENSE](LICENSE)).",
        "",
    ]
    for (data, link), users in sorted(sources.items()):
        lines += [f"## {data}", ""]
        if link:
            lines.append(f"- **Link:** {link}")
        licences = sorted(u for u in users if u.startswith("licence: "))
        lines += [f"- **Licence:** {lic[len('licence: '):]}" for lic in licences]
        lines.append("- **Used in:** " + ", ".join(f"`{u}`" for u in sorted(set(users) - set(licences))))
        lines.append("")
    return "\n".join(lines)


def changelog_entry(old_sha: str, new_sha: str, old_info: dict | None, new_info: dict) -> str:
    """Markdown entry for CHANGELOG.md when the warehouse lock moves."""
    old = {d["dataset"]: d["rows"] for d in (old_info or {}).get("datasets", [])}
    new = {d["dataset"]: d["rows"] for d in new_info["datasets"]}
    lines = [f"## {date.today().isoformat()}: warehouse `{old_sha[:12]}` → `{new_sha[:12]}`", ""]
    added, removed = sorted(set(new) - set(old)), sorted(set(old) - set(new))
    changed = sorted(n for n in set(new) & set(old) if new[n] != old[n])
    lines += [f"- Added: `{n}` ({new[n]:,} rows)" for n in added]
    lines += [f"- Removed: `{n}`" for n in removed]
    lines += [f"- Changed: `{n}` rows {old[n]:,} → {new[n]:,}" for n in changed]
    if not (added or removed or changed):
        lines.append("- No dataset added, removed or changed in row count.")
    return "\n".join(lines) + "\n\n"


def append_changelog(entry: str) -> None:
    path = ROOT / "CHANGELOG.md"
    header = "# Changelog\n\nOne entry each time `config/warehouse.lock` moves (`python build.py --update-lock`).\n\n"
    body = path.read_text(encoding="utf-8")[len(header):] if path.exists() else ""
    path.write_text(header + entry + body, encoding="utf-8")
