"""Collect warnings and decisions during a build and write BUILD_REPORT.md."""
from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class Report:
    warehouse_sha: str
    # section title -> list of markdown bullet lines (without the leading "- ")
    sections: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))

    def add(self, section: str, line: str) -> None:
        self.sections[section].append(line)

    def write(self, path: Path) -> None:
        # Fixed section order so the report is stable between runs.
        order = [
            "Datasets included",
            "Datasets skipped",
            "Lens assignment",
            "Merges",
            "State-total rows dropped",
            "Name-fallback matches",
            "Cleaning",
            "Column types",
            "Districts missing per dataset",
            "Column changes since last build",
            "Boundaries",
            "District profile",
            "Errors",
        ]
        lines = [
            "# Build report",
            "",
            f"Warehouse commit: `{self.warehouse_sha}`. Generated by `build.py`; do not edit.",
            "",
        ]
        for title in order + sorted(set(self.sections) - set(order)):
            items = self.sections.get(title)
            lines += [f"## {title}", ""]
            lines += [f"- {item}" for item in items] if items else ["- None."]
            lines.append("")
        path.write_text("\n".join(lines))
